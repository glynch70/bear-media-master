export function publicPackages() {
  return pricingPackages.map((p) => ({
    id: p.id,
    category: p.category,
    service: p.service,
    name: p.name,
    ctaLabel: p.ctaLabel,
    description: p.description,
    priceLabel:
      p.approvalStatus === "approved" ? formatPrice(p) : "Let’s agree a quote",
    includedDeliverables: p.scopeApproved ? p.includedDeliverables : [],
    exclusions: p.scopeApproved ? p.exclusions : [],
    optionalExtras: p.scopeApproved ? p.optionalExtras : [],
    revisionAllowance: p.scopeApproved ? p.revisionAllowance : null,
  }));
}
export type PublicPackage = ReturnType<typeof publicPackages>[number];
export function formatPrice(p: PricingPackage) {
  if (p.priceType === "bespoke") return "Bespoke quotation";
  const amount = new Intl.NumberFormat("en-GB", {
    style: "currency",
    currency: "GBP",
    maximumFractionDigits: 0,
  }).format(p.price);
  return `${p.priceType === "from" && p.billingPeriod !== "hour" ? "From " : ""}${amount}${p.billingPeriod === "month" ? "/month" : p.billingPeriod === "hour" ? `/hour · £${p.minimum} minimum` : ""}`;
}
